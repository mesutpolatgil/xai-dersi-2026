import torch
import torchvision.models as models
import torchvision.transforms as transforms
import matplotlib.pyplot as plt
from PIL import Image
import requests
from io import BytesIO
import numpy as np

# ==========================================
# KISIM 1: ResNet50 Model Yükleme ve Filtre Analizi
# ==========================================
print("=== KISIM 1: ResNet50 Model ve İlk Katman Filtre Analizi ===")
model = models.resnet50(pretrained=True)
model.eval()

# Broden veri seti formatına uygun örnek girdi tensörü simülasyonu
print("Broden veri seti formatına uygun örnek girdi tensörü hazırlanıyor...")
broden_sample_tensor = torch.randn(1, 3, 224, 224)

# Son evrişim katmanındaki (layer4) kanal aktivasyonlarını yakalama (Hook Mekanizması)
activation_maps = []
def hook_fn(module, input, output):
    activation_maps.append(output)

hook = model.layer4.register_forward_hook(hook_fn)
_ = model(broden_sample_tensor)
hook.remove()

feature_map = activation_maps[0]
print(f"Broden / Model Katman Aktivasyon Boyutu: {feature_map.shape}")

# İlk Katman Filtrelerinin Görselleştirilmesi
print("İlk katman filtre ağırlıkları görselleştiriliyor...")
weight_tensor = model.conv1.weight.data
filters = weight_tensor.cpu().numpy()

fig, axes = plt.subplots(8, 8, figsize=(10, 10))
for i, ax in enumerate(axes.flatten()):
    if i < 64:
        f_img = filters[i].mean(axis=0)
        f_img = (f_img - f_img.min()) / (f_img.max() - f_img.min() + 1e-5)
        ax.imshow(f_img, cmap='viridis')
    ax.axis('off')

plt.suptitle("27. Bölüm: Broden & ResNet50 İlk Katman Filtre Analizi", fontsize=13)
plt.tight_layout()
plt.savefig("learned_features_filters.png")
plt.show()
print("'learned_features_filters.png' dosyası kaydedildi.\n")


