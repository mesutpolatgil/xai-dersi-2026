import torch
import torchvision.models as models
import torchvision.transforms as transforms
import matplotlib.pyplot as plt
from PIL import Image
import requests
from io import BytesIO
import numpy as np

print("1. ResNet50 modeli yükleniyor...")
model = models.resnet50(pretrained=True)
model.eval()

# Örnek köpek görseli yükleme
print("2. Örnek girdi görseli indiriliyor...")
url = "https://images.unsplash.com/photo-1543466835-00a7907e9de1"
response = requests.get(url)
img = Image.open(BytesIO(response.content)).convert("RGB")

preprocess = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
    transforms.Normalize(mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]),
])
input_tensor = preprocess(img).unsqueeze(0)

# Hook mekanizması ile katman aktivasyonu yakalama
activation_maps = []
def hook_fn(module, input, output):
    activation_maps.append(output)

hook = model.layer4.register_forward_hook(hook_fn)
_ = model(input_tensor)
hook.remove()

feature_map = activation_maps[0].detach() # [1, 2048, 7, 7]
mask = feature_map.mean(dim=1)[0].numpy()
mask_resized = np.array(Image.fromarray(mask).resize((224, 224), Image.Resampling.BILINEAR))
mask_resized = (mask_resized - mask_resized.min()) / (mask_resized.max() - mask_resized.min() + 1e-5)

# Çoklu Panelli (Grid) Görselleştirme
print("3. Zenginleştirilmiş çoklu analiz paneli oluşturuluyor...")
fig, axes = plt.subplots(2, 3, figsize=(15, 10))

# 1. Panel: Orijinal Girdi
axes[0, 0].imshow(img.resize((224, 224)))
axes[0, 0].set_title("Orijinal Girdi Görseli")
axes[0, 0].axis('off')

# 2. Panel: İlk Katman Filtrelerinden Örnekler (conv1)
weight_tensor = model.conv1.weight.data.cpu().numpy()
sample_filter = weight_tensor[0].mean(axis=0)
sample_filter = (sample_filter - sample_filter.min()) / (sample_filter.max() - sample_filter.min() + 1e-5)
axes[0, 1].imshow(sample_filter, cmap='viridis')
axes[0, 1].set_title("İlk Katman (Conv1) Filtre Örneği")
axes[0, 1].axis('off')

# 3. Panel: 7x7 Ham Kanal Aktivasyonu (Network Dissection Katmanı)
axes[0, 2].imshow(mask, cmap='plasma')
axes[0, 2].set_title("7x7 Ham Kanal Aktivasyonu")
axes[0, 2].axis('off')

# 4. Panel: Büyütülmüş Isı Haritası (Maske)
axes[1, 0].imshow(mask_resized, cmap='jet')
axes[1, 0].set_title("Interpolasyonlu Isı Haritası")
axes[1, 0].axis('off')

# 5. Panel: Görsel Üzerine Giydirilmiş (Overlay) Aktivasyon Maskesi
axes[1, 1].imshow(img.resize((224, 224)), alpha=0.6)
axes[1, 1].imshow(mask_resized, cmap='jet', alpha=0.5)
axes[1, 1].set_title("Konsept Aktivasyon Örtüşmesi (Overlay)")
axes[1, 1].axis('off')

# 6. Panel: Aktivasyon Dağılım Histogramı (Kanal İstatistikleri)
axes[1, 2].hist(mask.flatten(), bins=20, color='purple', alpha=0.7)
axes[1, 2].set_title("Aktivasyon Değerleri Dağılımı")
axes[1, 2].set_xlabel("Aktivasyon Şiddeti")
axes[1, 2].set_ylabel("Frekans")

plt.suptitle("27. Bölüm: Kapsamlı Öğrenilmiş Özellikler ve Ağ Diseksiyonu Analizi", fontsize=15)
plt.tight_layout()
plt.savefig("chapter27_comprehensive_analysis.png")
plt.show()

print("İşlem Başarılı! 'chapter27_comprehensive_analysis.png' olarak kaydedildi.")