import torch
import torchvision.models as models
import matplotlib.pyplot as plt

print("1. VGG-16 modeli ImageNet ağırlıklarıyla yükleniyor...")
# Kitapta örneklerde ve kıyaslamalarda kullanılan VGG-16 modelini yüklüyoruz
model = models.vgg16(pretrained=True)
model.eval()

# Test için girdi tensörü oluşturma (Gerekirse gerçek bir görsel de yükleyebilirsiniz)
input_tensor = torch.randn(1, 3, 224, 224, requires_grad=True)
print("Girdi tensörü hazırlandı. Boyut:", input_tensor.shape)

print("\n2. İleri besleme (Forward Pass) ve Sınıf Skoru Hesaplanıyor...")
output = model(input_tensor)
target_class = output.argmax(dim=1)
score = output[0, target_class]
print(f"Tahmin edilen hedef sınıf ID: {target_class.item()}")

print("\n3. Vanilla Gradient (Geri Yayılım) Hesaplatılıyor...")
# Geri yayılım (Backward pass) ile gradyanları hesaplama
score.backward(retain_graph=True)

# Vanilla Saliency Map (Piksellere göre mutlak gradyanlar)
saliency, _ = torch.max(input_tensor.grad.data.abs(), dim=1)

print("\n4. SmoothGrad (Gürültü Enjeksiyonu ile Düzeltme) Simülasyonu Çalıştırılıyor...")
# Düzeltilen kısım: stdev_spread formülü tek satırda ve operatörler eklendi
stdev_spread = 0.1 * (input_tensor.max() - input_tensor.min())

smooth_saliency = torch.zeros_like(saliency)
n_samples = 15  # Örnek örneklem sayısı

for i in range(n_samples):
    # Düzeltilen kısım: Çarpma işlemi (*) eklendi ve syntax hatası giderildi
    noise_tensor = (input_tensor + torch.randn_like(input_tensor) * stdev_spread).clone().detach().requires_grad_(True)

    out_noise = model(noise_tensor)
    score_noise = out_noise[0, target_class]

    # Geri yayılım
    score_noise.backward()

    if noise_tensor.grad is not None:
        smooth_saliency += torch.max(noise_tensor.grad.data.abs(), dim=1)[0]

smooth_saliency /= n_samples
print("SmoothGrad hesaplaması hatasız tamamlandı!")

print("\n5. Sonuçlar Görselleştiriliyor ve Kaydediliyor...")
fig, axes = plt.subplots(1, 2, figsize=(10, 5))

axes[0].imshow(saliency[0].detach().numpy(), cmap='hot')
axes[0].set_title("Vanilla Gradient Haritası")
axes[0].axis('off')

axes[1].imshow(smooth_saliency[0].detach().numpy(), cmap='hot')
axes[1].set_title("SmoothGrad (Gürültüsü Giderilmiş) Haritası")
axes[1].axis('off')

plt.suptitle("28. Bölüm: Piksel Atıf Yöntemleri Karşılaştırması", fontsize=14)
plt.tight_layout()

# Görseli Colab dizinine kaydetme
plt.savefig("book_comparison_saliency.png")
plt.show()

print("İşlem Başarılı! Karşılaştırma görseli 'book_comparison_saliency.png' olarak kaydedildi.")

