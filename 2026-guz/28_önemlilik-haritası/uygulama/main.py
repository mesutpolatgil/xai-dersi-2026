import torch
import torchvision.models as models
import matplotlib.pyplot as plt
import numpy as np

print("1. VGG-16 modeli yükleniyor...")
model = models.vgg16(pretrained=True)
model.eval()

# Test için girdi tensörü
input_tensor = torch.randn(1, 3, 224, 224, requires_grad=True)

# İleri besleme ve hedef sınıf
output = model(input_tensor)
target_class = output.argmax(dim=1)
score = output[0, target_class]

# Vanilla Gradient
score.backward(retain_graph=True)
saliency, _ = torch.max(input_tensor.grad.data.abs(), dim=1)

# SmoothGrad Simülasyonu (Farklı gürültü örneklemleriyle)
stdev_spread = 0.1 * (input_tensor.max() - input_tensor.min())
smooth_saliency = torch.zeros_like(saliency)
n_samples = 20  # Örnek sayısını artırarak kararlılığı güçlendirdik

for i in range(n_samples):
    noise_tensor = (input_tensor + torch.randn_like(input_tensor) * stdev_spread).clone().detach().requires_grad_(True)
    out_noise = model(noise_tensor)
    score_noise = out_noise[0, target_class]
    score_noise.backward()
    if noise_tensor.grad is not None:
        smooth_saliency += torch.max(noise_tensor.grad.data.abs(), dim=1)[0]

smooth_saliency /= n_samples

# Çevirme numpy formatına
sal_np = saliency[0].detach().numpy()
smooth_np = smooth_saliency[0].detach().numpy()

# Çoklu Panelli (Grid) Karşılaştırma Görselleştirmesi
print("2. Zenginleştirilmiş 4'lü Saliency paneli oluşturuluyor...")
fig, axes = plt.subplots(2, 2, figsize=(12, 10))

# 1. Panel: Vanilla Gradient (Sıcak Harita)
im1 = axes[0, 0].imshow(sal_np, cmap='hot')
axes[0, 0].set_title("1. Vanilla Gradient Haritası")
axes[0, 0].axis('off')
fig.colorbar(im1, ax=axes[0, 0], fraction=0.046, pad=0.04)

# 2. Panel: SmoothGrad (Sıcak Harita - Gürültüsü Giderilmiş)
im2 = axes[0, 1].imshow(smooth_np, cmap='hot')
axes[0, 1].set_title("2. SmoothGrad Haritası (n=20)")
axes[0, 1].axis('off')
fig.colorbar(im2, ax=axes[0, 1], fraction=0.046, pad=0.04)

# 3. Panel: Eşiklenmiş (Thresholded) Vanilla
threshold = np.percentile(sal_np, 85) # En önemli %15'lik kısım
sal_thresh = np.where(sal_np > threshold, sal_np, 0)
im3 = axes[1, 0].imshow(sal_thresh, cmap='inferno')
axes[1, 0].set_title("3. Eşiklenmiş Vanilla (Yüksek Önemli Pikseller)")
axes[1, 0].axis('off')
fig.colorbar(im3, ax=axes[1, 0], fraction=0.046, pad=0.04)

# 4. Panel: Yöntemlerin Fark Haritası (Gürültü Farkı)
diff_map = np.abs(sal_np - smooth_np)
im4 = axes[1, 1].imshow(diff_map, cmap='coolwarm')
axes[1, 1].set_title("4. Vanilla ve SmoothGrad Fark Haritası")
axes[1, 1].axis('off')
fig.colorbar(im4, ax=axes[1, 1], fraction=0.046, pad=0.04)

plt.suptitle("28. Bölüm: Kapsamlı Piksel Atıf ve Gürültü Analizi Karşılaştırması", fontsize=14)
plt.tight_layout()
plt.savefig("chapter28_comprehensive_saliency.png")
plt.show()

print("İşlem Başarılı! 'chapter28_comprehensive_saliency.png' olarak kaydedildi.")